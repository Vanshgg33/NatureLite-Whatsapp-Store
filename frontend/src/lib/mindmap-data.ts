// Static explanation of the whole system, one record per module.
// in:   [source, what arrives]. `source` is a node id (clickable) or a plain actor ("Customer").
// steps: what the module does with it, in order.   formula: the real rules/maths, copied from the code.
// out:  the result it produces.                    to: [node id, what is handed over] (derived "receives from" is computed in the page).
export interface MMNode {
  id: string;
  label: string;
  desc: string;
  in: [string, string][];
  steps: string[];
  formula?: string[];
  out: string;
  href?: string;
  api?: string;
  to?: [string, string][];
}
export interface MMSystem {
  id: string;
  label: string;
  color: string;
  icon: string; // lucide icon name, resolved in the page
  summary: string;
  children: MMNode[];
}

type Opt = { formula?: string[]; href?: string; api?: string; to?: [string, string][] };
const n = (
  id: string, label: string, desc: string,
  inputs: [string, string][], steps: string[], out: string, o: Opt = {},
): MMNode => ({ id, label, desc, in: inputs, steps, out, ...o });

